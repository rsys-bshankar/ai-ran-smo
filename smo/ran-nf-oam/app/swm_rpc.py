"""The O-RAN software management RPCs a software job sends to its element (call flow 19): `software-download`, `software-install`, `software-activate`
(`o-ran-software-management.yang`, O-RAN WG4 M-Plane), over the element's O1 adaptor endpoint as a configuration edit is sent.

What it is: `build_rpc` makes the NETCONF `<rpc>` of a phase, and `send_phase` sends it to the endpoint the element is registered behind and reports the
outcome as the configuration clients do (`EditResult`: applied, reason, detail). The completion of a phase is not here: the element (its adaptor) reports it
with `POST /software-management-jobs/{id}/advance`, as the M-Plane's `download-event`, `install-event` and `activation-event` notifications do.

Owns: the XML of the three RPCs and the choice of transport. Does not own: the job's state (`lifecycle`), when a phase is sent (`lifecycle.dispatch_due`).
Phase 1: the slot is always `standby` and the file installed is the last segment of the remote path; RESTCONF endpoints are not sent software RPCs.
"""

from xml.sax.saxutils import escape, quoteattr

from sqlalchemy.orm import Session

from . import netconf_client, netconf_ssh
from .models import ManagedEntity, O1AdaptorEndpoint, O1AdaptorHostKey, SoftwareManagementJob
from .netconf_client import NETCONF_BASE_NS, EditResult

SWM_NS = "urn:o-ran:software-management:1.0"
SLOT = "standby"
RPC_OF_PHASE = {"DOWNLOAD": "software-download", "INSTALL": "software-install", "ACTIVATE": "software-activate"}


def build_rpc(message_id: str, phase: str, remote_file_path: str | None) -> str:
    """The `<rpc>` of `phase`: `software-download` with the `remote-file-path` (left out when the job has none: a revert job of a campaign), `software-install`
    of the file into the standby slot, `software-activate` of that slot. Every value is escaped; `message_id` is generated by the caller."""
    name = RPC_OF_PHASE[phase]
    file_name = (remote_file_path or "").rstrip("/").rsplit("/", 1)[-1]
    if phase == "DOWNLOAD":
        body = f"<remote-file-path>{escape(remote_file_path)}</remote-file-path>" if remote_file_path else ""
    elif phase == "INSTALL":
        body = f"<slot-name>{SLOT}</slot-name>" + (f"<file-names>{escape(file_name)}</file-names>" if file_name else "")
    else:
        body = f"<slot-name>{SLOT}</slot-name>"
    return f"<rpc message-id={quoteattr(message_id)} xmlns=\"{NETCONF_BASE_NS}\"><{name} xmlns=\"{SWM_NS}\">{body}</{name}></rpc>"


def send_phase(db: Session, job: SoftwareManagementJob, message_id: str) -> EditResult:
    """Sends the RPC of the job's current phase to its element's O1 adaptor: applied when the reply is `<ok/>`. Not applied, with a reason, when the element
    has no endpoint (`ENDPOINT_UNREACHABLE`), its endpoint is down, it is not reached over NETCONF (`PROTOCOL_NOT_SUPPORTED`), or the RPC fails or is refused."""
    me = db.get(ManagedEntity, job.managed_element_ref)
    endpoint = db.get(O1AdaptorEndpoint, me.o1_adaptor_endpoint_id) if me is not None and me.o1_adaptor_endpoint_id is not None else None
    if me is None or endpoint is None:
        return EditResult(False, "ENDPOINT_UNREACHABLE", "the element has no O1 adaptor endpoint")
    if endpoint.health_status in ("UNREACHABLE", "DEGRADED"):
        return EditResult(False, "ENDPOINT_UNREACHABLE", f"the element's O1 adaptor endpoint is {endpoint.health_status}")
    if me.o1_protocol != "NETCONF":
        return EditResult(False, "PROTOCOL_NOT_SUPPORTED", f"software management RPCs are sent over NETCONF, the element is reached over {me.o1_protocol}")
    rpc = build_rpc(message_id, job.phase, job.remote_file_path)
    if endpoint.transport in ("ssh", "tls"):
        keys = [(k.key_type, k.public_key) for k in db.query(O1AdaptorHostKey).filter(O1AdaptorHostKey.endpoint_id == endpoint.endpoint_id)]
        return netconf_ssh.send_rpc(endpoint.adaptor_uri, rpc, endpoint.credential_ref, keys if endpoint.transport == "ssh" else None)
    return netconf_client.send_rpc(endpoint.adaptor_uri, rpc)
