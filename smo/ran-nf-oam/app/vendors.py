class ScopeBody(BaseModel):
    """Where an element is and whom it belongs to (PR-SEC-10.2): `null` clears it. Both keys replace the stored values."""
    model_config = ConfigDict(extra="forbid")
    region: str | None = Field(default=None, max_length=100)
    tenant: str | None = Field(default=None, max_length=100)

    @field_validator("region", "tenant")
    @classmethod
    def _valid(cls, value: str | None) -> str | None:
        if value is not None and not authz_scope.valid_value(value):
            raise ValueError("must be 1 to 100 characters of letters, digits and . _ : / @ + -, starting with a letter or digit")
        return value


@router.put("/managed-entities/{managed_element_ref}/scope")
def set_managed_entity_scope(managed_element_ref: str, body: ScopeBody, db: Session = Depends(get_session)):
    """PR-SEC-10.2: set the `region` and `tenant` of a managed element (an operator's or an SMO module's call; an rApp is refused at the gateway). Replaces both;
    a key left out or `null` clears it, and an element with no region (tenant) is then for unscoped callers, and for callers whose claim does not restrict
    regions (tenants), only. Takes effect on the next request. 404 for an unknown element."""
    me = _get_me(db, managed_element_ref)
    me.region, me.tenant = body.region, body.tenant
    db.commit()
    return {"managedElementRef": me.managed_element_ref, "region": me.region, "tenant": me.tenant}


@router.put("/managed-entities/{managed_element_ref}/cells/{cell_id}/guards")
def set_cell_guards(managed_element_ref: str, cell_id: str, body: CellGuardBody, request: Request, db: Session = Depends(get_session)):
    # 403 SCOPE_DENIED outside the caller's scope, 404 for an unknown element. Replaces the whole guard record of that cell (other cells are kept) and commits; the cell id is not checked against the element's cells.
    scoping.require_elements(db, scoping.request_scope(request), [managed_element_ref])        # PR-SEC-10.9: 403 SCOPE_DENIED outside the caller's scope
    me = _get_me(db, managed_element_ref)
    me.cell_guards = {**(me.cell_guards or {}), cell_id: body.model_dump()}  # reassign: JSON columns don't track in-place edits
    db.commit()
    return {"managedElementRef": managed_element_ref, "cellId": cell_id, **body.model_dump()}


@router.delete("/managed-entities/{managed_element_ref}/cells/{cell_id}/guards", status_code=204)
def delete_cell_guards(managed_element_ref: str, cell_id: str, request: Request, db: Session = Depends(get_session)):
    # 403 SCOPE_DENIED outside the caller's scope, 404 for an unknown element; 204 whether or not the cell had a guard record.
    scoping.require_elements(db, scoping.request_scope(request), [managed_element_ref])        # PR-SEC-10.9: 403 SCOPE_DENIED outside the caller's scope
    me = _get_me(db, managed_element_ref)
    if cell_id in (me.cell_guards or {}):
        me.cell_guards = {k: v for k, v in me.cell_guards.items() if k != cell_id}
        db.commit()


@router.get("/cell-guards")
def query_cell_guards(request: Request, managed_element_ref: str | None = None, cell_id: str | None = None, cell_class: CellClass | None = None,
                      sector_group: str | None = None, incident_zone: str | None = None, region: str | None = scoping.RegionFilter,
                      site_cluster: str | None = scoping.SiteClusterFilter, limit: int = PageLimit,
                      offset: int = PageOffset, db: Session = Depends(get_session)):
    """The guard query any rApp uses (e.g. the EnergySaving rApp never
    sleeps an EMERGENCY cell, nor two cells of one sectorGroup at once). PR-SEC-10.6: only the elements inside the caller's scope claim.
    PR-GUI-9.3: `region` and `site_cluster` keep the cells of the elements of that place."""
    stmt = scoping.scoped_to_elements(select(ManagedEntity), scoping.request_scope(request), ManagedEntity.managed_element_ref).order_by(ManagedEntity.managed_element_ref)
    stmt = scoping.narrowed_to_place(stmt, ManagedEntity.managed_element_ref, region, site_cluster)
    stmt = msac.readable(stmt, db, request, ManagedEntity.managed_element_ref)                       # MGT-2.6
    if managed_element_ref:
        stmt = stmt.where(ManagedEntity.managed_element_ref == managed_element_ref)
    items = []
    for me in db.scalars(stmt):
        for cid, guard in sorted((me.cell_guards or {}).items()):
            if (cell_id and cid != cell_id) or (cell_class and guard["cellClass"] != cell_class) \
                    or (sector_group and guard.get("sectorGroup") != sector_group) \
                    or (incident_zone and guard.get("incidentZone") != incident_zone):
                continue
            items.append({"managedElementRef": me.managed_element_ref, "cellId": cid, **guard})
    return paginate_list(items, limit, offset)
