"""Multi-vendor O1 framework — Wave 9 (HISTORY.md W9-01..06),
building `docs/ARCHITECTURE.md`'s sketch.

Onboarding a vendor is data, not code:

  * **Capability Registry** (W9-01/W9-04) — `PUT /vendor-capabilities/{vendor}`:
    the MnS services the vendor's O1 terminations implement (axis 2, a
    presence list), its data-model conformance (axis 3: `OWN` / `SPEC` /
    `COMBINED`, with `schemaRef` = the vendor's own descriptor and
    `specSchemaRef` = the spec descriptor), and the O1 transports it speaks
    (`supportedVendorModes`: `O1_NETCONF` / `O1_RESTCONF`).
  * **CM schema descriptors** (W9-02) — `POST /cm-schemas`: `CMSchemaCache`
    finally gets a writer and a reader. A descriptor (`{"classes": {IOC:
    {attribute: {type, enum?}}}}`) is generated by
    `scripts/ingest_cm_schema.py`; the 3GPP TS 28.541 NR NRM one is bundled
    (`app/cm_schemas/`) as the default spec descriptor.
  * **Vendor onboarding** (W9-03) — `POST /vendor-onboarding`: discover the
    vendor's declared capabilities from its adaptor, load its schema(s),
    declare its capability, in one call. Endpoints then register through the
    unchanged `POST /o1-adaptor-endpoints` with `vendorName`.

Two generic checks read the registry at request time — no per-vendor
branching anywhere: `require_service` (an ME whose vendor doesn't implement
FM/PM/SWM/PROV is refused before anything is created) and
`schema_problems` (a CM write is checked against the descriptor(s) its
vendor's conformance mode selects). An ME with no vendor capability
registered skips both, the permissive default the guide specifies.

Cell guard attributes (W9-06, decision D-5) live on `ManagedEntity` and are
queryable by any rApp (`GET /cell-guards`).
"""

