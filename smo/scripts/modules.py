"""The module manifests: each module says what it is to the rest of the SMO in one file of its own, `<module>/module.yaml` (schema:
`scripts/module.schema.json`), and the shared files that used to list every module are generated from, or read from, those manifests.

So a pull request that adds a module, or changes how one is wired (its compose service, chart entry, database role, tables, R1 route, coverage floor, ...),
edits only that module's folder, and two such pull requests merge in either order (CLAUDE.md, "Working in parallel"; history.d/MODULE-MANIFESTS.md).

    python scripts/modules.py            # validate every manifest and check it against the module's files (the default: --check)
    python scripts/modules.py --write    # also rewrite the generated files
    python scripts/modules.py --check    # fail when a generated file differs from what the manifests give (CI job `lint`)
    python scripts/modules.py list unit-suites   # one line per unit suite: NAME DIR SOURCE PYTHONPATH (scripts/run_unit_suite.sh's arguments)
    python scripts/modules.py list openapi       # the modules scripts/generate_openapi_specs.py writes a spec of
    python scripts/modules.py list mutation      # one line per mutation-tested module: DIR PYTHONPATH (scripts/mutation_pilot.sh)
    python scripts/modules.py list database      # the modules with a database role (scripts/check_migration_matches_models.py)

Generated (committed, so a reviewer sees each change, and `--check` fails on one edited by hand):
- `docker-compose.yml`: the regions between `# >>> modules` and `# <<< modules` in `services:`, `secrets:`, `networks:` and `volumes:`, each module's
  text verbatim under a header naming its manifest, in the order of the modules' paths; and the `migrate` service's list of module password secrets;
- `deploy/helm/smo/values.yaml`: the same region under `modules:`;
- `migrations/db_roles.json` and `migrations/table_owners.json` (the keys starting with `_` are kept from the file);
- `r1-termination/app/routes.json`: R1 Termination's static routes (read by its `app/main.py` at import, and by `tests_integration/mesh.py`);
- `.github/workflows/smo-mutation.yml`: the region of its `pull_request` paths.
Read at run time: the unit suites and their coverage floors (`scripts/coverage_floor.py`, the CI job `unit-and-integration`), the OpenAPI list, the
mutation runs and the database modules (the `list` commands above).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

import yaml

SMO = Path(__file__).resolve().parent.parent
REPO = SMO.parent
SCHEMA = SMO / "scripts" / "module.schema.json"
MANIFEST = "module.yaml"

BEGIN = "# >>> modules: generated by scripts/modules.py from each <module>/module.yaml ({what}); edit those, then run it with --write"
END = "# <<< modules"


class ManifestError(Exception):
    """One or more manifests are invalid, or disagree with their module's files: the message lists every problem."""


@dataclass(frozen=True)
class Module:
    """One manifest: `path` is the module's directory relative to smo/ (`aimgf`, `samples/energy-saving-rapp`), `data` the parsed YAML."""

    path: str
    data: dict

    @property
    def name(self) -> str:
        """The module's name (its directory's last part)."""
        return self.data["name"]

    def get(self, key: str):
        """The manifest's value of `key`."""
        return self.data[key]


def manifest_paths(root: Path = SMO) -> list[Path]:
    """Every manifest under `root`: `<module>/module.yaml` and `samples/<rapp>/module.yaml`, in path order."""
    found = list(root.glob(f"*/{MANIFEST}")) + list(root.glob(f"samples/*/{MANIFEST}"))
    return sorted(found, key=lambda p: p.parent.relative_to(root).as_posix())


def load(root: Path = SMO) -> list[Module]:
    """Every manifest, validated against the schema; raises ManifestError naming each invalid one."""
    from jsonschema import Draft202012Validator

    validator = Draft202012Validator(json.loads(SCHEMA.read_text(encoding="utf-8")))
    modules, problems = [], []
    for path in manifest_paths(root):
        where = path.relative_to(root).as_posix()
        try:
            data = yaml.safe_load(path.read_text(encoding="utf-8"))
        except yaml.YAMLError as exc:
            problems.append(f"{where}: not YAML: {exc}")
            continue
        errors = sorted(validator.iter_errors(data), key=lambda e: list(e.path))
        problems += [f"{where}: {'/'.join(map(str, e.path)) or '(top)'}: {e.message}" for e in errors]
        if not errors:
            modules.append(Module(path.parent.relative_to(root).as_posix(), data))
    if problems:
        raise ManifestError("\n".join(problems))
    return modules


def _top_keys(text: str) -> list[str]:
    """The keys at column 0 of a manifest's YAML text (a compose section, the chart's entries)."""
    return [m.group(1) for m in re.finditer(r"^([A-Za-z0-9_.-]+):", text, re.MULTILINE)]


def _is_module_dir(directory: Path) -> bool:
    """Whether `directory` holds Python code of a module: a file in app/ or tests/ (a folder with only caches left behind is not one)."""
    return any(next((directory / sub).glob("*.py"), None) for sub in ("app", "tests"))


def consistency(modules: list[Module], root: Path = SMO) -> list[str]:
    """What the manifests get wrong about their modules and about each other: one line per problem (empty when none)."""
    problems = []
    paths = {m.path for m in modules}
    candidates = [p for p in root.iterdir() if p.is_dir()] + [p for p in (root / "samples").iterdir() if p.is_dir()]
    for directory in sorted(candidates):
        rel = directory.relative_to(root).as_posix()
        if rel not in paths and _is_module_dir(directory):
            problems.append(f"{rel}/: a module with no {MANIFEST}")
    seen: dict[tuple[str, str], str] = {}

    def unique(kind: str, value: str, owner: str) -> None:
        """Records that `owner` claims `value` of `kind`; a second claimant is a problem."""
        if (kind, value) in seen and seen[(kind, value)] != owner:
            problems.append(f"{owner}: {kind} {value} is also {seen[(kind, value)]}'s")
        seen.setdefault((kind, value), owner)

    for m in modules:
        where = f"{m.path}/{MANIFEST}"
        if m.name != m.path.rsplit("/", 1)[-1]:
            problems.append(f"{where}: name {m.name} is not the directory's name")
        for route in m.get("r1"):
            unique("R1 prefix", route["prefix"], m.path)
            unique("R1 address variable", route["env"], m.path)
        database = m.get("database")
        if database:
            if database["role"] and database["role"]["schema"]:
                unique("database schema", database["role"]["schema"], m.path)
            for table in database["tables"]:
                unique("table", table, m.path)
        tests = m.get("tests")
        packaged = (root / m.path / "app").is_dir() or any((root / m.path).glob("smo_*/__init__.py"))
        if not tests and packaged and next((root / m.path / "tests").glob("test_*.py"), None):
            problems.append(f"{where}: the module has a package and tests/, but no `tests` (its unit suite would not run, nor its coverage be held)")
        if tests and not (root / m.path / tests["source"]).is_dir():
            problems.append(f"{where}: tests.source {tests['source']} is not a directory of the module")
        if tests and not (root / m.path / "tests").is_dir():
            problems.append(f"{where}: tests is set but the module has no tests/")
        pyproject = root / m.path / "pyproject.toml"
        configured = None
        if pyproject.exists():
            configured = tomllib.loads(pyproject.read_text(encoding="utf-8")).get("tool", {}).get("mutmut", {}).get("only_mutate")
        mutation = m.get("mutation")
        if mutation and configured != mutation["targets"]:
            problems.append(f"{where}: mutation.targets differ from {m.path}/pyproject.toml's [tool.mutmut] only_mutate")
        code_docs = (root / "scripts" / "code_docs_baseline" / (m.path.replace("/", "--") + ".json")).exists()
        if m.get("code_docs") != code_docs:
            problems.append(f"{where}: code_docs is {m.get('code_docs')}, but scripts/code_docs_baseline/ {'has' if code_docs else 'has no'} file of it")
        config = (root / "docs" / "configuration" / f"{m.name}.md").exists()
        if m.get("config_reference") != config:
            problems.append(f"{where}: config_reference is {m.get('config_reference')}, but docs/configuration/ {'has' if config else 'has no'} {m.name}.md")
        compose = m.get("compose") or {}
        for section, text in compose.items():
            try:
                parsed = yaml.safe_load(_anchors_stubbed(text))
            except yaml.YAMLError as exc:
                problems.append(f"{where}: compose.{section} is not YAML: {exc}")
                continue
            if not isinstance(parsed, dict):
                problems.append(f"{where}: compose.{section} is not a mapping")
                continue
            for key in parsed:
                unique(f"compose {section[:-1]}", key, m.path)
                if section == "services" and key != m.name and not key.startswith(m.name + "-"):
                    problems.append(f"{where}: compose service {key} is not named {m.name} or {m.name}-<role>")
        if m.get("helm"):
            for key in _top_keys(m.get("helm")):
                unique("chart module", key, m.path)
                if key != m.name and not key.startswith(m.name + "-"):
                    problems.append(f"{where}: chart module {key} is not named {m.name} or {m.name}-<role>")
    return problems


def _anchors_stubbed(text: str) -> str:
    """A compose section's text with the file's aliases (`*hardening`, `<<: *db_env`) made parseable on their own."""
    text = re.sub(r"<<: \*[a-z_]+,?\s*", "", text)
    return re.sub(r"\*[a-z_]+", "null", text)


# ---------------------------------------------------------------- generated text


def _indent(text: str, by: int) -> list[str]:
    """`text`'s lines indented by `by` spaces (empty lines stay empty)."""
    return [(" " * by + line) if line.strip() else "" for line in text.rstrip("\n").split("\n")]


def _region(blocks: list[tuple[str, str]], what: str, indent: int) -> list[str]:
    """The lines of a generated region: a begin marker, each (module path, text) under a header, an end marker. A header line and a blank line
    stand between two modules, so changes to two different modules never touch neighbouring lines."""
    pad = " " * indent
    out = [pad + BEGIN.format(what=what)]
    for path, text in blocks:
        out.append(f"{pad}# --- {path}/{MANIFEST}")
        out += _indent(text, indent)
        out.append("")
    out.append(pad + END)
    return out


def _replace_region(lines: list[str], section: str, region: list[str], file: str) -> list[str]:
    """`lines` with the region under `section:` replaced by `region` (both markers must be there, once each)."""
    start = lines.index(f"{section}:") if f"{section}:" in lines else None
    if start is None:
        raise ManifestError(f"{file}: no top-level `{section}:`")
    end = next((i for i in range(start + 1, len(lines)) if lines[i] and not lines[i].startswith((" ", "#"))), len(lines))
    begins = [i for i in range(start, end) if lines[i].startswith("  # >>> modules")]          # at the section's own indent
    ends = [i for i in range(start, end) if lines[i] == "  " + END]
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        raise ManifestError(f"{file}: `{section}:` needs one `# >>> modules` line and one `{END}` line after it")
    return lines[: begins[0]] + region + lines[ends[0] + 1:]


def compose_text(modules: list[Module], current: str) -> str:
    """docker-compose.yml with its module regions generated, and the module password secrets (one line each) of `migrate` (which makes the roles) and
    `pgbouncer` (which logs each role in)."""
    lines = current.split("\n")
    for section in ("services", "secrets", "networks", "volumes"):
        blocks = [(m.path, m.get("compose")[section]) for m in modules if m.get("compose") and section in m.get("compose")]
        lines = _replace_region(lines, section, _region(blocks, f"compose.{section}", 2), "docker-compose.yml")
    secrets = [f"db_password_{m.name}" for m in modules if (m.get("database") or {}).get("role")]
    begins = [i for i, line in enumerate(lines) if line.strip() == BEGIN.format(what="database.role")]
    if len(begins) != 2:
        raise ManifestError("docker-compose.yml: `migrate` and `pgbouncer` each need a `# >>> modules ... (database.role)` region in their `secrets:` list")
    for begin in reversed(begins):
        end = next((i for i in range(begin + 1, len(lines)) if lines[i].strip() == END), None)
        if end is None:
            raise ManifestError(f"docker-compose.yml: line {begin + 1}: a region with no `{END}` line")
        pad = lines[begin][: len(lines[begin]) - len(lines[begin].lstrip())]
        lines[begin + 1:end] = [f"{pad}- {s}" for s in secrets]
    return "\n".join(lines)


def values_text(modules: list[Module], current: str) -> str:
    """The chart's values.yaml with its `modules:` region generated."""
    blocks = [(m.path, m.get("helm")) for m in modules if m.get("helm")]
    return "\n".join(_replace_region(current.split("\n"), "modules", _region(blocks, "helm", 2), "deploy/helm/smo/values.yaml"))


def _json(data: dict) -> str:
    """The JSON layout of the migrations' files (one-space indent, a final newline)."""
    return json.dumps(data, indent=1, ensure_ascii=False) + "\n"


def _with_notes(current: str, generated: dict) -> dict:
    """`generated` between the current file's `_` keys: the ones before its first module stay first, the others last."""
    old = json.loads(current) if current else {}
    keys = list(old)
    first_module = next((i for i, k in enumerate(keys) if not k.startswith("_")), len(keys))
    head = {k: old[k] for k in keys[:first_module] if k.startswith("_")}
    tail = {k: old[k] for k in keys[first_module:] if k.startswith("_")}
    return {**head, **generated, **tail}


def db_roles_text(modules: list[Module], current: str) -> str:
    """migrations/db_roles.json: each module's role, keyed by its path."""
    roles = {m.path: m.get("database")["role"] for m in modules if (m.get("database") or {}).get("role")}
    return _json(_with_notes(current, roles))


def table_owners_text(modules: list[Module], current: str) -> str:
    """migrations/table_owners.json: each module's tables, keyed by its path."""
    owners = {m.path: list(m.get("database")["tables"]) for m in modules if m.get("database")}
    return _json(_with_notes(current, owners))


def routes_text(modules: list[Module], current: str = "") -> str:
    """r1-termination/app/routes.json: R1 Termination's static routes, prefix -> the module, the variable that overrides its address, the default."""
    routes = {r["prefix"]: {"module": m.name, "env": r["env"], "url": r["url"]} for m in modules for r in m.get("r1")}
    return _json({"_comment": "Generated by scripts/modules.py from each module's module.yaml (r1); do not edit. Read by app/main.py (ROUTES).",
                  **dict(sorted(routes.items()))})


def mutation_workflow_text(modules: list[Module], current: str) -> str:
    """smo-mutation.yml with the module region of its pull_request paths generated."""
    lines = current.split("\n")
    begins = [i for i, line in enumerate(lines) if line.strip().startswith("# >>> modules")]
    ends = [i for i, line in enumerate(lines) if line.strip() == END]
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        raise ManifestError(f".github/workflows/smo-mutation.yml: needs one `# >>> modules` line and one `{END}` line after it")
    pad = lines[begins[0]][: len(lines[begins[0]]) - len(lines[begins[0]].lstrip())]
    region = [pad + BEGIN.format(what="mutation.watch")]
    for m in modules:
        if m.get("mutation"):
            region.append(f"{pad}# --- {m.path}/{MANIFEST}")
            region += [f'{pad}- "{w}"' for w in m.get("mutation")["watch"]]
    region.append(pad + END)
    return "\n".join(lines[: begins[0]] + region + lines[ends[0] + 1:])


GENERATED = {
    SMO / "docker-compose.yml": compose_text,
    SMO / "deploy" / "helm" / "smo" / "values.yaml": values_text,
    SMO / "migrations" / "db_roles.json": db_roles_text,
    SMO / "migrations" / "table_owners.json": table_owners_text,
    SMO / "r1-termination" / "app" / "routes.json": routes_text,
    REPO / ".github" / "workflows" / "smo-mutation.yml": mutation_workflow_text,
}


def generate(modules: list[Module], files: dict = GENERATED) -> dict[Path, tuple[str, str]]:
    """{file: (current text, generated text)} for each generated file."""
    out = {}
    for path, make in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        out[path] = (current, make(modules, current))
    return out


# ---------------------------------------------------------------- read at run time


def unit_suites(modules: list[Module] | None = None) -> list[tuple[str, str, str, str]]:
    """(name, dir, source, pythonpath) of every unit suite, in path order."""
    return [(m.name, m.path, m.get("tests")["source"], m.get("tests")["pythonpath"]) for m in (modules or load()) if m.get("tests")]


def coverage_floors(modules: list[Module] | None = None) -> dict[str, float]:
    """{suite name: coverage floor}."""
    return {m.name: m.get("tests")["floor"] for m in (modules or load()) if m.get("tests")}


def openapi_modules(modules: list[Module] | None = None) -> list[str]:
    """The paths of the modules with an OpenAPI spec."""
    return [m.path for m in (modules or load()) if m.get("openapi")]


def database_modules(modules: list[Module] | None = None) -> list[str]:
    """The paths of the modules with a database role of their own."""
    return [m.path for m in (modules or load()) if (m.get("database") or {}).get("role")]


def mutation_runs(modules: list[Module] | None = None) -> list[tuple[str, str]]:
    """(dir, pythonpath) of every mutation-tested module, the shared library first (the others' runs import it)."""
    runs = [(m.path, m.get("mutation")["pythonpath"]) for m in (modules or load()) if m.get("mutation")]
    return sorted(runs, key=lambda r: r[0] != "shared")


def set_floor(name: str, floor: float, root: Path = SMO) -> None:
    """Rewrites the `floor:` of suite `name` in its manifest (scripts/coverage_floor.py --write), leaving the rest of the file as it is."""
    module = next(m for m in load(root) if m.name == name and m.get("tests"))
    path = root / module.path / MANIFEST
    text = path.read_text(encoding="utf-8")
    new, count = re.subn(r"^(tests: \{.*floor: )[0-9.]+(\})", lambda mt: f"{mt.group(1)}{floor:g}{mt.group(2)}", text, flags=re.MULTILINE)
    if count != 1:
        raise ManifestError(f"{path.relative_to(root)}: no one-line `tests: {{..., floor: N}}` to rewrite")
    path.write_text(new, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    """Validates the manifests; with --write rewrites the generated files, otherwise fails on one that differs. `list` prints what a script reads."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("command", nargs="?", choices=["list"])
    parser.add_argument("what", nargs="?", choices=["unit-suites", "openapi", "mutation", "database"])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        modules = load()
    except ManifestError as exc:
        print(f"FAIL: invalid module manifests:\n{exc}", file=sys.stderr)
        return 1
    if args.command == "list":
        rows = {"unit-suites": [" ".join(s) for s in unit_suites(modules)], "openapi": openapi_modules(modules),
                "mutation": [" ".join(r) for r in mutation_runs(modules)], "database": database_modules(modules)}[args.what or parser.error("list what?")]
        print("\n".join(rows))
        return 0
    problems = consistency(modules)
    try:
        generated = generate(modules)
    except ManifestError as exc:
        problems.append(str(exc))
        generated = {}
    stale = []
    for path, (current, new) in generated.items():
        if current != new:
            if args.write:
                path.write_text(new, encoding="utf-8")
                print(f"wrote {path.relative_to(REPO)}")
            else:
                stale.append(path.relative_to(REPO).as_posix())
    problems += [f"{s}: differs from what the module manifests give (run: python scripts/modules.py --write)" for s in stale]
    if problems:
        print("FAIL:\n" + "\n".join(f"  {p}" for p in problems), file=sys.stderr)
        return 1
    print(f"OK: {len(modules)} module manifests, every generated file current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
